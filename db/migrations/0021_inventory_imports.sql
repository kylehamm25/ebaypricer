-- EbayPrice: photo imports for the unlisted inventory pile.
-- Paste into Supabase SQL editor (Dashboard > SQL Editor) and run once, after 0020.
-- Created IF NOT EXISTS so the script is idempotent.

-- ==============================================================
-- A scan is a question - "which card is in this photo, and how sure are we?" - and
-- this table is where that question waits until somebody answers it. The inventory
-- row itself is only created on confirm, through the same write path as a hand-added
-- row. Keeping the import separate means a wrong OCR guess cannot become stock
-- silently, and an auto-added row has something to point at when it is undone.
--
-- The photo is stored before the row exists (photo_storage.upload_import), because
-- the image is the only durable record of what was scanned and the review screen
-- needs to show it even when recognition fails. Confirming copies that URL into
-- inventory.photo_urls; the import row keeps it for the recent/undo list.
--
-- candidates is the top few catalog printings the recognizer found, in rank order.
-- It is jsonb rather than a child table because it is a snapshot of what the model
-- thought at scan time - not a relation anything joins against.
--
-- status: pending (awaiting review), confirmed (inventory row linked), dismissed
-- (photo removed, no row), failed (recognition could not run or found nothing).
-- auto_added records that the page confirmed it without a person reviewing it, which
-- is what makes the Undo action safe to offer.
-- ==============================================================

create table if not exists public.inventory_imports (
    id                bigint generated by default as identity primary key,
    user_id           uuid not null references auth.users(id) on delete cascade,
    image_url         text not null,
    source_filename   text,
    status            text not null default 'pending'
        check (status in ('pending', 'confirmed', 'dismissed', 'failed')),
    auto_added        boolean not null default false,
    confidence        text not null default 'none'
        check (confidence in ('high', 'medium', 'low', 'none')),
    score             numeric(4,3) check (score is null or (score >= 0 and score <= 1)),
    card_detected     boolean not null default false,
    ocr_text          text,
    detected_name     text,
    detected_number   text,
    candidates        jsonb not null default '[]'::jsonb,
    chosen_card_query text,
    inventory_id      bigint references public.inventory(id) on delete set null,
    error             text,
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now()
);

-- The queue reads pending/failed rows oldest first, and the recent list reads
-- auto-added confirmations newest first. One index serves both.
create index if not exists idx_inventory_imports_user_status
    on public.inventory_imports (user_id, status, created_at desc);

alter table public.inventory_imports enable row level security;

-- User-owned, same shape as inventory and lots. The backend writes via
-- service_role, which bypasses RLS; this policy is what lets a user read their own.
drop policy if exists "inventory_imports_owner_all" on public.inventory_imports;
create policy "inventory_imports_owner_all" on public.inventory_imports
    for all to authenticated
    using (user_id = auth.uid())
    with check (user_id = auth.uid());
